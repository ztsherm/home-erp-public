export type RecordIconName = keyof typeof iconByName;

export function normalizeRecordIcon(value: string | null | undefined) {
  return value && value in iconByName ? (value as RecordIconName) : null;
}

export function RecordIcon({ name, className = "h-5 w-5" }: { name?: string | null; className?: string }) {
  const normalized = normalizeRecordIcon(name);
  const Icon = normalized ? iconByName[normalized] : Circle;
  return <Icon className={className} aria-hidden="true" />;
}
